import math
import os
from pathlib import Path


def _yaw_from_quaternion(orientation):
    siny_cosp = 2.0 * (
        orientation.w * orientation.z + orientation.x * orientation.y
    )
    cosy_cosp = 1.0 - 2.0 * (
        orientation.y * orientation.y + orientation.z * orientation.z
    )
    return math.atan2(siny_cosp, cosy_cosp)


def _pixel(value):
    if value < 0:
        return 205
    if value >= 65:
        return 0
    if value <= 25:
        return 254
    return 205


def _atomic_write(path, data):
    temporary = path.with_name(f".{path.name}.tmp")
    try:
        with temporary.open("wb") as output:
            output.write(data)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def save_occupancy_grid(message, directory, basename="map"):
    """Save a ROS OccupancyGrid as a Nav2-compatible PGM/YAML pair."""
    width = int(message.info.width)
    height = int(message.info.height)
    resolution = float(message.info.resolution)
    if width <= 0 or height <= 0:
        raise ValueError("OccupancyGrid width and height must be positive")
    if not math.isfinite(resolution) or resolution <= 0.0:
        raise ValueError("OccupancyGrid resolution must be finite and positive")
    if len(message.data) != width * height:
        raise ValueError(
            f"OccupancyGrid has {len(message.data)} cells; expected {width * height}"
        )

    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    pgm_path = directory / f"{basename}.pgm"
    yaml_path = directory / f"{basename}.yaml"

    # OccupancyGrid starts at the lower-left; PGM scanlines start at the top.
    pixels = bytearray(width * height)
    output_index = 0
    for row in range(height - 1, -1, -1):
        input_index = row * width
        for column in range(width):
            pixels[output_index] = _pixel(int(message.data[input_index + column]))
            output_index += 1

    header = (
        f"P5\n# ROS OccupancyGrid generated by rrc_slam_manager\n"
        f"{width} {height}\n255\n"
    ).encode("ascii")
    _atomic_write(pgm_path, header + pixels)

    origin = message.info.origin
    yaw = _yaw_from_quaternion(origin.orientation)
    yaml = (
        f"image: {basename}.pgm\n"
        "mode: trinary\n"
        f"resolution: {resolution:.12g}\n"
        f"origin: [{origin.position.x:.12g}, {origin.position.y:.12g}, {yaw:.12g}]\n"
        "negate: 0\n"
        "occupied_thresh: 0.65\n"
        "free_thresh: 0.25\n"
    ).encode("utf-8")
    _atomic_write(yaml_path, yaml)
    return pgm_path, yaml_path
